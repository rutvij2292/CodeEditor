#!/usr/bin/env node
// One-off generator for Sources/CodeEditor/NativeWebDataGen.swift: CSS properties / at-rules / pseudo selectors and HTML elements /
// attributes from the MDN-derived data that ships with the MIT licensed vscode-css-languageservice / vscode-html-languageservice
// (found in vscode-langservers-extracted). Descriptions are shortened; the output is a table of immortal string literals (read lazily).
// Usage: node scripts/make-web-data.js [path to vscode-langservers-extracted/node_modules] > Sources/CodeEditor/NativeWebDataGen.swift
const base = process.argv[2] || (process.env.HOME + '/.nvm/versions/node/v20.19.5/lib/node_modules/vscode-langservers-extracted/node_modules/');
const css = require(base + 'vscode-css-languageservice/lib/umd/data/webCustomData.js').cssData;
const html = require(base + 'vscode-html-languageservice/lib/umd/languageFacts/data/webCustomData.js').htmlData;

function plain(d, max) {
  if (!d) return '';
  let s = typeof d === 'string' ? d : (d.value || '');
  s = s.replace(/\[([^\]]+)\]\([^)]*\)/g, '$1').replace(/[`*_]{1,2}/g, '').replace(/\s+/g, ' ').trim();
  if (s.length > max) {
    const cut = s.lastIndexOf('. ', max);
    s = cut > max * 0.5 ? s.slice(0, cut + 1) : s.slice(0, max).replace(/\s+\S*$/, '') + '...';
  }
  return s;
}
function lit(s) {
  let out = '"';
  for (const ch of s) {
    const c = ch.codePointAt(0);
    if (ch === '"') out += '\\"';
    else if (ch === '\\') out += '\\\\';
    else if (c < 32) out += '\\u{' + c.toString(16) + '}';
    else if (c > 126) out += '\\u{' + c.toString(16) + '}';
    else out += ch;
  }
  return out + '"';
}
const SEP1 = '\u0001', SEP2 = '\u0002', SEP3 = '\u0003';
const lines = [];
function emit(name, arr) {
  lines.push('    static let ' + name + ': [String] = [');
  for (const a of arr) lines.push('        ' + lit(a) + ',');
  lines.push('    ]');
}

const cssProps = css.properties.filter(p => !p.name.startsWith('-moz-') || ['-moz-osx-font-smoothing', '-moz-appearance'].includes(p.name)).map(p => {
  const values = (p.values || []).map(v => v.name).filter(n => n && !/\s/.test(n)).join(' ');
  const obsolete = p.status === 'obsolete' || p.status === 'nonstandard' ? 'x' : '';
  return [p.name, plain(p.description, 230), values, (p.syntax || '').slice(0, 120), obsolete].join(SEP1);
});
const at = css.atDirectives.map(a => [a.name, plain(a.description, 200)].join(SEP1));
const pc = css.pseudoClasses.map(a => [a.name, plain(a.description, 200)].join(SEP1));
const pe = css.pseudoElements.map(a => [a.name, plain(a.description, 200)].join(SEP1));

const sets = {};
for (const vs of html.valueSets) sets[vs.name] = vs.values.map(v => v.name);
function attrEntry(a) {
  const values = a.valueSet && sets[a.valueSet] ? sets[a.valueSet] : (a.values || []).map(v => v.name);
  return [a.name, plain(a.description, 200), values.filter(v => !/\s/.test(v)).join(' ')].join(SEP3);
}
const tags = html.tags.map(t => [t.name, plain(t.description, 230), (t.attributes || []).map(attrEntry).join(SEP2)].join(SEP1));
const globals = html.globalAttributes.map(attrEntry);

lines.push('// Generated by scripts/make-web-data.js from vscode-css-languageservice / vscode-html-languageservice (MIT, MDN derived data). Do not edit.');
lines.push('// Record layout: fields separated by U+0001; HTML attribute lists by U+0002 with fields by U+0003.');
lines.push('enum NWWebDataGen {');
emit('cssProperties', cssProps);
emit('cssAtRules', at);
emit('cssPseudoClasses', pc);
emit('cssPseudoElements', pe);
emit('htmlTags', tags);
emit('htmlGlobalAttributes', globals);
lines.push('}');
process.stdout.write(lines.join('\n') + '\n');
